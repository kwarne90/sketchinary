function uniqueWords(lists: string[][]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const list of lists) {
    for (const word of list) {
      const key = word.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      out.push(word);
    }
  }
  return out;
}

export function wordsFor(set: WordSet): string[] {
  switch (set) {
    case "disney":
      return DISNEY_WORDS;
    case "hard":
      return HARD_WORDS;
    case "movies":
      return getMovieShowWords();
    case "animals":
      return ANIMAL_WORDS;
    case "combined":
      return uniqueWords([
        BASIC_WORDS,
        DISNEY_WORDS,
        HARD_WORDS,
        ANIMAL_WORDS,
        getMovieShowWords(),
      ]);
    default:
      return BASIC_WORDS;
  }
}

export function pickWord(used: string[], set: WordSet = "basic"): string {
  const words = wordsFor(set);
  const pool = words.filter((word) => !used.includes(word));
  const source = pool.length > 0 ? pool : words;
  return source[Math.floor(Math.random() * source.length)];
}
